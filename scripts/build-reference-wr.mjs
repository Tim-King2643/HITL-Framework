#!/usr/bin/env node
// Reference lookup for the Worker (GR-054).
//
// The Worker must not take an activity's Consequence of Error, Progression
// Ceiling or ceiling factors from the page when it checks a ceiling
// override. This script extracts them from the one place they are
// authored, WR_DATA in docs/sandbox/pcf7.html, into
// docs/sandbox/reference-wr.json, which is deployed with the site's static
// assets. The Worker reads that file (env.ASSETS) and checks every override
// against it.
//
// The output carries a version: a short hash of its own activity data, so an
// override records which version of the reference it was approved against.
// The file has no timestamp, so the same WR_DATA always gives the same file.
//
// Usage:
//   node scripts/build-reference-wr.mjs          write the file
//   node scripts/build-reference-wr.mjs --check  fail if the file is missing
//                                                or out of date (run in CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";

const SRC = "docs/sandbox/pcf7.html";
const OUT = "docs/sandbox/reference-wr.json";

const html = readFileSync(SRC, "utf8");
const start = html.indexOf("const WR_DATA = {");
if (start < 0) throw new Error("WR_DATA not found in " + SRC);
const open = html.indexOf("{", start);
const close = html.indexOf("\n};", open);
if (close < 0) throw new Error("end of WR_DATA not found in " + SRC);
// WR_DATA is a plain object literal of strings and arrays; evaluate just it.
const WR_DATA = new Function("return " + html.slice(open, close + 2))();

const activities = {};
for (const code of Object.keys(WR_DATA).sort((a, b) => a.localeCompare(b, "en", { numeric: true }))) {
  const d = WR_DATA[code];
  activities[code] = { ceiling: d.ceiling, cons: d.cons, ceilingFactors: d.ceilingFactors || [] };
}
const version = createHash("sha256").update(JSON.stringify(activities)).digest("hex").slice(0, 12);
const text = JSON.stringify({
  source: SRC,
  note: "Generated by scripts/build-reference-wr.mjs from WR_DATA. Do not edit by hand.",
  version,
  count: Object.keys(activities).length,
  activities
}, null, 1) + "\n";

if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== text) {
    console.error(OUT + " is out of date with WR_DATA in " + SRC + ".\nRun: node scripts/build-reference-wr.mjs, and commit the result.");
    process.exit(1);
  }
  console.log(OUT + " is up to date (version " + version + ", " + Object.keys(activities).length + " activities).");
} else {
  writeFileSync(OUT, text);
  console.log("Wrote " + OUT + " (version " + version + ", " + Object.keys(activities).length + " activities).");
}
